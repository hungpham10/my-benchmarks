def _csv_rows(total, variant, t_start_ms, interval_s, window_min):
    """Yield rows for COPY into metrics_jsonb / metrics_norm_brin plus series_dim.

    series_dim (metric, job, instance, region, service) is emitted first so the
    autogenerated identity id matches series_id used in metrics_norm_brin rows
    (series_id = enumerate position + 1). Both metric families (counter + gauge)
    are loaded so q1–q5 all run on real data instead of returning empty sets.
    """
    from datetime import datetime, timezone

    # Build series descriptors using shared dataset module — counter and gauge.
    series = d.build_series()

    # Generate timestamps for the window
    # We need timestamps matching the Prometheus scrape intervals
    interval_ms = interval_s * 1000
    n_samples = int(window_min * 60 / interval_s)

    # Generate values using shared values module (same as Prometheus)
    # generate_chunk returns (n_series, n_samples) array for both counter & gauge.
    timestamps = v.generate_timestamps(t_start_ms)
    values = v.generate_chunk(series)

    series_dim_rows = []
    sample_rows = []
    for s, desc in enumerate(series):
        series_id = s + 1  # matches autogenerated series_dim.id (identity from 1)
        lbls = d.labels_json(desc)  # unique label set per series, matching Prometheus
        series_dim_rows.append(
            (desc["metric"], desc["job"], desc["instance"], desc["region"], desc["service"])
        )
        for i in range(n_samples):
            ts_iso = datetime.fromtimestamp(timestamps[i] / 1000, tz=timezone.utc).isoformat()
            val = values[s, i]
            if variant in ("norm", "sharded"):
                # time, series_id, value - unique series_id per series
                sample_rows.append((ts_iso, series_id, val))
            else:
                # time, labels, value - unique labels per series
                sample_rows.append((ts_iso, lbls, val))
    return series_dim_rows, sample_rows


def init_modshard(cur, total, t_start_ms, t_end_ms, interval_s, window_min):
    """Variant 'modshard': application-side modulo sharding study.

    The question: is it worth fanning writes out over N physical tables
    (user_id % N -> events_XX), and at what cost in DDL, TOAST and GIN?
    The dataset is the benchctl series machinery (user_id = series_id, so
    series_dim stays the join table and the metric filters keep working);
    the only thing that changes between legs is the physical layout and
    the secondary indexes.

    Env (set from the scenario legs):
      SHARD_LAYOUT  A single table (baseline)
                    B N tables events_00.., routed user_id % N
                    C 8 schemas x N/4 tables (namespace-only control)
                    D layout B + payload jsonb (GIN variants via SHARD_INDEX)
                    E declarative PARTITION BY HASH (user_id)
      SHARD_INDEX   I1 btree (user_id, created_at desc)
                    I2 btree (user_id)
                    I3 D + GIN jsonb_ops (fastupdate=on)
                    I4 D + GIN jsonb_path_ops (fastupdate=off)
                    I5 D + generated kind + btree (user_id, kind)
      SHARD_N       shard count (default 32)

    Rows are COPYed into the physical targets, so the measured
    init_seconds is the bulk-insert cost of exactly this layout on exactly
    this filesystem — the number the report axis is built on. A read-only
    VIEW events_all (time, series_id, value) gives the query side the same
    contract as metrics_norm_brin, so the catalog and read shapes reuse.
    """
    import hashlib

    # Leg dimensions from the driver arrive uppercase with the leg's key
    # name (LAYOUT, INDEX); SHARD_* names are the legacy/self-doc forms.
    layout = (os.environ.get("LAYOUT") or os.environ.get("SHARD_LAYOUT") or "B")
    index_id = (os.environ.get("INDEX") or os.environ.get("SHARD_INDEX")
                or "I1")
    # SHARDS comes from a leg dimension (pg-shard-n.yaml), SHARD_N from the
    # scenario env; the leg wins so one scenario can sweep the count.
    n = int(os.environ.get("SHARDS") or os.environ.get("SHARD_N") or 32)
    has_jsonb = layout == "D" or index_id == "I5"
    kind_gen = (", kind text GENERATED ALWAYS AS (payload->>'kind') STORED"
                if index_id == "I5" else "")

    cols = ("time timestamptz NOT NULL, series_id bigint NOT NULL, "
            "value double precision NOT NULL")
    payload_cols = (", payload jsonb" + kind_gen) if has_jsonb else ""
    full_cols = "time, series_id, value" + (", payload" if has_jsonb else "")

    def create_rw(name):
        cur.execute(f"""
            CREATE TABLE {name} (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                {cols}{payload_cols}
            )""")

    cur.execute("DROP TABLE IF EXISTS events CASCADE")
    cur.execute("DROP VIEW IF EXISTS events_all CASCADE")
    cur.execute("DROP TABLE IF EXISTS events_defunct CASCADE")

    targets = []
    if layout == "A":
        create_rw("events")
        targets = [("events", None)]
        cur.execute("CREATE VIEW events_all AS "
                    "SELECT time, series_id, value FROM events")
    elif layout == "E":
        # Identity columns are not supported on a partitioned parent, and
        # the PK must include the partition key. (series_id, time) is the
        # natural uniqueness here: one sample per series per interval.
        cur.execute(f"""
            CREATE TABLE events (
                time timestamptz NOT NULL,
                series_id bigint NOT NULL,
                value double precision NOT NULL,
                PRIMARY KEY (series_id, time)
            ) PARTITION BY HASH (series_id)""")
        for i in range(n):
            cur.execute(f"""
                CREATE TABLE events_p{i} PARTITION OF events
                FOR VALUES WITH (MODULUS {n}, REMAINDER {i})""")
        targets = [("events", None)]  # same shape for store+view contract
        cur.execute("CREATE VIEW events_all AS "
                    "SELECT time, series_id, value FROM events")
    elif layout == "C":
        for i in range(8):
            cur.execute(f"CREATE SCHEMA IF NOT EXISTS s{i:02d}")
        for i in range(n):
            qual = f"s{i // 4:02d}.events_{i % 4:02d}"
            create_rw(qual)
            targets.append((qual, i))
        cur.execute("CREATE VIEW events_all AS " + " UNION ALL ".join(
            f"SELECT time, series_id, value FROM s{i // 4:02d}.events_{i % 4:02d}"
            for i in range(n)))
    else:  # layout B / D
        for i in range(n):
            qual = f"events_{i:02d}"
            create_rw(qual)
            targets.append((qual, i))
        cur.execute("CREATE VIEW events_all AS " + " UNION ALL ".join(
            f"SELECT time, series_id, value FROM events_{i:02d}"
            for i in range(n)))
    print(f"[init] modshard: layout={layout} index={index_id} n={n} "
          f"targets={len(targets)}", flush=True)

    # Secondary indexes BEFORE the COPY, so the measured cost is the real
    # index-maintenance cost of inserting into this layout (mirrors how a
    # production workload pays GIN).
    for qual, _ in targets:
        safe = qual.replace(".", "_")
        if layout == "D":
            gin_sql = {
                "I3": (f"CREATE INDEX gin_jb_{safe} ON {qual} "
                       "USING gin (payload jsonb_ops) WITH (fastupdate=on)"),
                "I4": (f"CREATE INDEX gin_jb_{safe} ON {qual} "
                       "USING gin (payload jsonb_path_ops) "
                       "WITH (fastupdate=off)"),
            }.get(index_id)
            if gin_sql:
                cur.execute(gin_sql)
        if index_id in ("I1", "I3", "I4"):
            cur.execute(f"CREATE INDEX btree_uc_{safe} ON {qual} "
                        "(series_id, time)")
        elif index_id == "I2":
            cur.execute(f"CREATE INDEX btree_u_{safe} ON {qual} (series_id)")
        elif index_id == "I5":
            cur.execute(f"CREATE INDEX btree_uk_{safe} ON {qual} "
                        "(series_id, kind)")

    # ---- rows: same series machinery as the norm variant --------------
    series = d.build_series()
    window_samples = int(window_min * 60 / interval_s)
    timestamps = v.generate_timestamps(t_start_ms)
    values = v.generate_chunk(series)

    from datetime import datetime, timezone

    def iso(ms):
        return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).isoformat()

    payload_of = None
    if has_jsonb:
        def payload_of(series_id):
            rng = 40 if series_id % 5 == 0 else 16
            return json.dumps({
                "kind": "kind_" + str(series_id % 20).zfill(2),
                "tags": ["alpha", "beta"],
                "attrs": {"blob": hashlib.md5(
                    str(series_id).encode()).hexdigest() * rng},
            })

    n_rows = 0
    t0 = time.monotonic()
    # One CSV buffer per target; rows route by series_id % n (mod sharding)
    writers = []
    for qual, shard in targets:
        buf = io.StringIO()
        w = csv.writer(buf)
        w.writerow(("time", "series_id", "value") + (("payload",) if has_jsonb else ()))
        writers.append((qual, shard, buf, w))

    for s, desc in enumerate(series):
        series_id = s + 1
        shard = series_id % n if targets and targets[0][1] is not None else None
        for i in range(window_samples):
            ts = iso(timestamps[i])
            val = float(values[s, i])
            row_payload = payload_of(series_id) if payload_of else ""
            # For a single-table layout everything goes to one writer; for
            # a sharded layout the row's writer is picked by modulo.
            wsel = 0 if shard is None else shard
            qual, shard2, buf, wr = writers[wsel]
            if has_jsonb:
                wr.writerow([ts, series_id, val, row_payload])
            else:
                wr.writerow([ts, series_id, val])
            n_rows += 1

    samples_per_writer = n_rows // max(len(writers), 1)
    for qual, shard, buf, wr in writers:
        buf.seek(0)
        with cur.copy(
            f"COPY {qual} ({full_cols}) FROM STDIN WITH (FORMAT CSV, HEADER)"
        ) as copy:
            copy.write(buf.read())
    seconds = time.monotonic() - t0

    # series_dim AFTER the measured COPY: it is constant across legs, and
    # the metric filters + counter sums all join through it.
    series_dim_rows = [(desc["metric"], desc["job"], desc["instance"],
                        desc["region"], desc["service"]) for desc in series]
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["metric", "job", "instance", "region", "service"])
    for r in series_dim_rows:
        writer.writerow(r)
    buf.seek(0)
    with cur.copy(
        "COPY series_dim (metric, job, instance, region, service) "
        "FROM STDIN WITH (FORMAT CSV, HEADER)"
    ) as copy:
        copy.write(buf.read())

    return {"samples": n_rows, "seconds": round(seconds, 1),
            "samples_per_second": round(n_rows / seconds, 1) if seconds > 0 else 0,
            "requests": 1, "layout": layout, "index": index_id,
            "shard_n": n}


def init_userdb(cur):
    """Variant 'userdb': the plain user-management schema.

    The metrics datasets hide the filesystem behind bulk COPY and the
    write size of a scrape. This variant is the opposite: a users table
    with a couple of small rows and three equally small indexes. What the
    FS comparison actually measures here are per-statement index
    maintenance and the WAL fsync rate the layout's write path asks for.

    The register leg varies:
      LAYOUT  A single table (baseline)
              B N tables users_00.., routed by user_id % N
              C The same as B but spread over 8 schemas (namespace control)
              E declarative PARTITION BY HASH (user_id)
      MODE    none   no payload column at all (bare layout costs)
              jsonb  payload jsonb, not indexed (TOAST cost only)
              gin    payload jsonb + GIN jsonb_path_ops index

    10M rows are seeded server-side (generate_series), so the measured
    init_seconds is the bulk cost of the layout. The insert phase itself
    is driven by k6 (one small transaction per arrival) — that is the
    number the report is built on.
    """
    layout = (os.environ.get("LAYOUT")
              or os.environ.get("SHARD_LAYOUT") or "A")
    mode = os.environ.get("MODE", "none")
    n = int(os.environ.get("SHARDS")
            or os.environ.get("SHARD_N") or 32)
    # POOLS is the pool dimension: user_id % P picks the pool, pool == 1
    # schema, 1 table per schema. LAYOUT C is exactly this; the table
    # count inside a pool stays at 1 (pool routing is the sharding key).
    pools = int(os.environ.get("POOLS") or n)
    total = int(os.environ.get("N_USERS") or "10000000")

    cur.execute("CREATE EXTENSION IF NOT EXISTS citext")
    cur.execute("DROP TABLE IF EXISTS users CASCADE")
    cur.execute("DROP VIEW IF EXISTS users_all CASCADE")
    cur.execute("DROP SCHEMA IF EXISTS s00, s01, s02, s03, s04, s05, s06, s07 CASCADE")

    # Column set per mode. payload grows by a deterministic blob profile;
    # 30% of the rows carry a >2KB blob so TOAST engages on the seeded set
    # too, not just on the k6 phase.
    cols = ("user_id bigint NOT NULL, email citext NOT NULL, name text, "
            "created_at timestamptz NOT NULL DEFAULT now()")
    payload_col = ", payload jsonb" if mode != "none" else ""
    payload_name = ", payload" if mode != "none" else ""

    payload_sel = ""
    if mode != "none":
        # tier: five values; attrs.blob: md5 hex repeated — 30% long
        payload_sel = (", jsonb_build_object("
                       "'tier', 'tier_' || mod(i, 5), "
                       "'tags', to_jsonb(array['alpha','beta','gamma']), "
                       "'attrs', jsonb_build_object("
                       "'blob', repeat(md5(i::text), "
                       "CASE WHEN mod(i, 10) < 3 THEN 40 ELSE 16 END)))")

    targets = []
    def create_rw(name):
        cur.execute(f"""
            CREATE TABLE {name} (
                user_id bigint NOT NULL,
                email citext NOT NULL,
                name text,
                created_at timestamptz NOT NULL DEFAULT now(){payload_col},
                PRIMARY KEY (user_id)
            )""")
        cur.execute(f"CREATE UNIQUE INDEX uq_email_{name.replace('.', '_')} "
                    f"ON {name} (email)")
        cur.execute(f"CREATE INDEX ix_created_{name.replace('.', '_')} "
                    f"ON {name} (created_at)")
        if mode == "gin":
            cur.execute(f"CREATE INDEX gin_prof_{name.replace('.', '_')} "
                        f"ON {name} USING gin (payload jsonb_path_ops)")

    if layout == "A":
        create_rw("users")
        targets = [("users", None)]
        cur.execute("CREATE VIEW users_all AS SELECT * FROM users")
    elif layout == "E":
        # DB-side routing: declarative hash partitioning. Not as a
        # partitioned table it needs its own GIN/unique inside the
        # parent — indexes on the parent cascade to partitions.
        cur.execute(f"""
            CREATE TABLE users (
                user_id bigint NOT NULL,
                email citext NOT NULL,
                name text,
                created_at timestamptz NOT NULL DEFAULT now(){payload_col},
                PRIMARY KEY (user_id)
            ) PARTITION BY HASH (user_id)""")
        # A declared-hash partitioned table cannot enforce a global
        # unique(e-mail): every unique index must include the partition
        # key. (email, user_id) is the closest legal form; it guarantees
        # one row per (user_id, email) — the "log in with the same email
        # on two shards" hole is a REAL architectural cost of this
        # layout and the report says so, instead of hiding it.
        cur.execute("CREATE UNIQUE INDEX uq_email_users "
                    "ON users (email, user_id)")
        cur.execute("CREATE INDEX ix_created_users ON users (created_at)")
        if mode == "gin":
            cur.execute("CREATE INDEX gin_prof_users ON users "
                        "USING gin (payload jsonb_path_ops)")
        for i in range(n):
            cur.execute(f"""
                CREATE TABLE users_p{i} PARTITION OF users
                FOR VALUES WITH (MODULUS {n}, REMAINDER {i})""")
        targets = [("users", None)]
        cur.execute("CREATE VIEW users_all AS SELECT * FROM users")
    elif layout == "C":
        # Pool-per-schema: P schemas s00.., each holding exactly ONE
        # users table. user_id % P picks the pool; a connection that
        # belongs to pool p never touches another schema. The seed routes
        # the same way, so every schema holds the users of its pool.
        for i in range(pools):
            cur.execute(f"CREATE SCHEMA IF NOT EXISTS s{i:02d}")
            qual = f"s{i:02d}.users"
            create_rw(qual)
            targets.append((qual, i))
        cur.execute("CREATE VIEW users_all AS " + " UNION ALL ".join(
            f"SELECT * FROM s{i:02d}.users" for i in range(pools)))
    else:  # layout B
        for i in range(n):
            qual = f"users_{i:02d}"
            create_rw(qual)
            targets.append((qual, i))
        cur.execute("CREATE VIEW users_all AS " + " UNION ALL ".join(
            f"SELECT * FROM users_{i:02d}" for i in range(n)))

    print(f"[init] userdb: layout={layout} mode={mode} n={n} "
          f"pools={pools} users={total}", flush=True)

    # ---- bulk seed: server-side generate_series ------------------------
    # Straight INSERT per shard, single backend at a time (comparable to
    # the other modules' bulk COPY). synchronous_commit is off here: the
    # fsync-per-commit question is EXACTLY the k6 leg's question, and the
    # seed must not pay it a million times.
    cur.execute("SET synchronous_commit = off")
    t0 = time.monotonic()
    route_mod = pools if layout == "C" else n
    for tname, shard in targets:
        if shard is None:
            cond = ""
        else:
            cond = f" WHERE mod(i, {route_mod}) = {shard}"
        cur.execute(f"""
            INSERT INTO {tname} (user_id, email, name, created_at{payload_name})
            SELECT i,
                   'user' || i || '@example.com',
                   'User ' || i,
                   now() - (mod(i, 730) * interval '1 day'){payload_sel}
            FROM generate_series(1, {total}) g(i){cond}
        """)
    cur.execute("SET synchronous_commit = on")
    seconds = time.monotonic() - t0

    return {"samples": total, "seconds": round(seconds, 1),
            "samples_per_second": round(total / seconds, 1) if seconds > 0 else 0,
            "requests": 1, "layout": layout, "mode": mode, "shard_n": n}


def init_idxlab(cur):
    """Variant 'idxlab': one table, one index type per leg.

    The userdb legs answer the layout question with btree everywhere.
    This variant asks the INDEX question: given the same 10M-row table,
    how does each access method change the write bill (bulk seed, index
    build, transactional maintenance) and which one wins which read
    shape? The columns are chosen so each AM has a case it claims:

      id         bigint PK      btree (baseline, always present)
      created_at timestamptz    BRIN vs btree range scans (monotonic
                                with insertion order — the correlation
                                BRIN needs)
      rating     int            hash vs btree plain equality
      loc        point          GiST vs SP-GiST kNN
      name       text           SP-GiST text vs btree prefix LIKE
      tags       text[]         GIN (array containment reference);

    IX selects the extra index: none | btree_name | brin_time |
    hash_rating | gist_point | spgist_point | spgist_name | gin_trgm.
    The index is built AFTER the bulk seed so the build itself is a
    measured number, and the k6 phase then pays per-statement
    maintenance on the finished structure.
    """
    ix = os.environ.get("IX", "none")
    total = int(os.environ.get("N_USERS") or "10000000")

    cur.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")
    cur.execute("DROP TABLE IF EXISTS docs CASCADE")
    cur.execute("""
        CREATE TABLE docs (
            id         bigint      NOT NULL,
            created_at timestamptz NOT NULL,
            rating     int         NOT NULL,
            loc        point       NOT NULL,
            name       text        NOT NULL,
            tags       text[]      NOT NULL,
            PRIMARY KEY (id)
        )""")

    print(f"[init] idxlab: ix={ix} rows={total}", flush=True)

    # ---- bulk seed (server-side generate_series, synchronous_commit off
    # for the same reason as userdb: fsync-per-commit is the k6 question)
    cur.execute("SET synchronous_commit = off")
    t0 = time.monotonic()
    cur.execute(f"""
        INSERT INTO docs (id, created_at, rating, loc, name, tags)
        SELECT i,
               '2020-01-01'::timestamptz + (i * interval '1 minute'),
               mod(i, 100000),
               point(mod(i, 10000), mod(i * 3, 10000)),
               'User ' || i,
               ARRAY['t' || mod(i, 25), 'tag' || mod(i, 7)]
        FROM generate_series(1, {total}) g(i)
    """)
    seed_seconds = round(time.monotonic() - t0, 1)
    cur.execute("SET synchronous_commit = on")

    # ---- the index under test, built over the seeded table
    builds = {
        "none": "",
        "btree_name": "CREATE INDEX ix_name ON docs (name)",
        "brin_time": "CREATE INDEX ix_time ON docs USING brin (created_at)",
        "hash_rating": "CREATE INDEX ix_rating ON docs USING hash (rating)",
        "gist_point": "CREATE INDEX ix_loc ON docs USING gist (loc)",
        "spgist_point": "CREATE INDEX ix_loc ON docs USING spgist (loc)",
        "spgist_name": "CREATE INDEX ix_name ON docs USING spgist (name text_pattern_ops)",
        "gin_trgm": ("CREATE INDEX ix_name_trgm ON docs "
                     "USING gin (name gin_trgm_ops)"),
    }
    if ix not in builds:
        raise SystemExit(f"unknown IX {ix!r}")
    build_seconds = 0.0
    if builds[ix]:
        t0 = time.monotonic()
        cur.execute(builds[ix])
        build_seconds = round(time.monotonic() - t0, 1)

    # Size of the table + the extra index: absolute bytes per index mode,
    # independent of the leg's workload.
    idx_rel = {"btree_name": "ix_name", "brin_time": "ix_time",
               "hash_rating": "ix_rating", "gist_point": "ix_loc",
               "spgist_point": "ix_loc", "spgist_name": "ix_name",
               "gin_trgm": "ix_name_trgm"}.get(ix, "")
    cur.execute("SELECT pg_total_relation_size('docs')")
    doc_bytes = int(cur.fetchone()[0])
    idx_bytes = 0
    if idx_rel:
        cur.execute(f"SELECT pg_relation_size('{idx_rel}')")
        idx_bytes = int(cur.fetchone()[0])

    seconds = seed_seconds
    return {"samples": total, "seconds": seconds,
            "samples_per_second": round(total / seconds, 1) if seconds > 0 else 0,
            "index_build_seconds": build_seconds,
            "docs_bytes": doc_bytes,
            "index_bytes": idx_bytes,
            "requests": 1, "ix": ix}
    """Load dataset into the SUT PostgreSQL.

    The driver has already:
      - started the SUT container and set env vars (PG_DSN, VARIANT)
      - created the schema via 01_schema.sql on compose up
      - placed dataset.json in results/ with total_samples, etc.

    We COPY exactly that many rows so pg_stat_statements counts them.
    """
    # ---- resolve DSN -------------------------------------------------
    # The driver runs on the host, not in the Docker network, so we must
    # use localhost with the mapped port. The driver sets PG_PORT env var.
    port = os.environ.get("PG_PORT", "15432")
    dsn = os.environ.get("PG_DSN")
    if not dsn:
        dsn = f"postgres://bench:bench@localhost:{port}/bench?sslmode=disable"
    else:
        # Override host/port in the provided DSN to use localhost:mapped_port
        # PG_DSN from module.yaml uses 'sut' which only works inside Docker network
        from urllib.parse import urlparse, urlunparse
        parsed = urlparse(dsn)
        # Preserve username and password from the original DSN
        netloc = f"{parsed.username}:{parsed.password}@localhost:{port}" if parsed.username else f"localhost:{port}"
        dsn = urlunparse((
            parsed.scheme,
            netloc,
            parsed.path,
            parsed.params,
            parsed.query,
            parsed.fragment
        ))

    # ---- read total_samples from dataset.json -----------------------
    # Use RESULTS_DIR env var if set by driver, else compute from file location
    results_dir = os.environ.get(
        "RESULTS_DIR",
        os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results"))
    ds_path = os.path.join(results_dir, "dataset.json")
    total = 1200  # fallback smoke number
    t_start_ms = 0
    t_end_ms = 0
    interval_s = 15
    window_min = 45
    if os.path.exists(ds_path):
        with open(ds_path) as f:
            m = json.load(f)
        total = m.get("total_samples", 1200)
        t_start_ms = m.get("t_start_ms", 0)
        t_end_ms = m.get("t_end_ms", 0)
        interval_s = m.get("interval_seconds", 15)
        window_min = m.get("window_minutes", 45)
        # Debug: print what we read
        print(f"[init] read dataset: total={total}, t_start_ms={t_start_ms}, t_end_ms={t_end_ms}, interval_s={interval_s}, window_min={window_min}", file=sys.stderr)
    else:
        print(f"[init] dataset.json not found at {ds_path}, using fallback", file=sys.stderr)

    # Fallback: if dataset.json is missing or invalid, compute from scenario params
    if t_start_ms == 0:
        ahead_min = int(os.environ.get("AHEAD_MINUTES", "8"))
        window_min = int(os.environ.get("WINDOW_MINUTES", "45"))
        interval_s = int(os.environ.get("INTERVAL_SECONDS", "15"))
        now_ms = int(time.time() * 1000)
        t_start_ms = int(time.time() * 1000) - (window_min - ahead_min) * 60 * 1000
        t_end_ms = t_start_ms + window_min * 60 * 1000
        print(f"[init] fallback timestamps: t_start_ms={t_start_ms}, t_end_ms={t_end_ms}, interval_s={interval_s}, window_min={window_min}", file=sys.stderr)

    # ---- decide variant ---------------------------------------------
    variant = os.environ.get("VARIANT", "jsonb")  # overridden per-leg

    # ---- ensure partitions exist --------------------------------------
    def ensure_partitions(cur, t_start_ms, t_end_ms):
        """Create daily partitions for the time range."""
        from datetime import datetime, timezone
        start_day = int(t_start_ms) // 1000 // 86400
        end_day = int(t_end_ms) // 1000 // 86400
        for day_offset in range(end_day - start_day + 1):
            day_ts = (start_day + day_offset) * 86400
            day_str = datetime.fromtimestamp(day_ts, tz=timezone.utc).strftime("%Y-%m-%d")
            for table in ["metrics_jsonb", "metrics_norm_brin"]:
                cur.execute(
                    "SELECT bench_ensure_partitions(%s::regclass, %s::date)",
                    (table, day_str)
                )

    # ---- connect and ensure partitions --------------------------------------
    conn = psycopg.connect(dsn, autocommit=True)
    cur = conn.cursor()

    # Parallel workers. 0 by default: on one CPU a parallel plan buys
    # nothing and costs reproducibility (the workers allocate dynamic shared
    # memory in /dev/shm, which is 64 MB in Docker and charged to the
    # container's memory limit). The sharding scenario asks for workers,
    # because its whole question is how much of the machine a query can use.
    #
    # ALTER SYSTEM, not a command-line -c: a command-line option beats
    # postgresql.auto.conf, so the loader could never raise it again.
    workers = int(os.environ.get("BENCHCTL_PARALLEL_WORKERS", "0") or 0)
    cur.execute(f"ALTER SYSTEM SET max_parallel_workers_per_gather = {workers}")
    cur.execute(f"ALTER SYSTEM SET max_parallel_workers = {max(workers, 8)}")
    cur.execute("SELECT pg_reload_conf()")
    print(f"[init] max_parallel_workers_per_gather = {workers}", flush=True)

    if t_start_ms and t_end_ms:
        ensure_partitions(cur, t_start_ms, t_end_ms)

    # ---- app-side modulo sharding variant has its own init path -------
    if variant == "modshard":
        res = init_modshard(cur, total, t_start_ms, t_end_ms,
                            interval_s, window_min)
        conn.commit()
        cur.close()
        conn.close()
        # series_dim must exist for the metric filters; load it after the
        # measurement COPY so its own COPY time is not measured (it is
        # constant across layout legs anyway).
        return res

    # ---- user-management variant: tiny rows, many small transactions --
    if variant == "userdb":
        res = init_userdb(cur)
        conn.commit()
        cur.close()
        conn.close()
        return res

    # ---- index-lab variant: one table, one access method per leg ------
    if variant == "idxlab":
        res = init_idxlab(cur)
        conn.commit()
        cur.close()
        conn.close()
        return res

    # ---- generate rows using timestamps from dataset.json
    series_dim_rows, sample_rows = _csv_rows(total, variant, t_start_ms, interval_s, window_min)
    samples = len(sample_rows)

    # COPY series_dim first so metrics_norm_brin.series_id matches the
    # autogenerated identity id (series_dim.id starts at 1, in insert order).
    if series_dim_rows:
        buf = io.StringIO()
        writer = csv.writer(buf)
        writer.writerow(["metric", "job", "instance", "region", "service"])
        for r in series_dim_rows:
            writer.writerow(r)
        buf.seek(0)
        with cur.copy(
            "COPY series_dim (metric, job, instance, region, service) "
            "FROM STDIN WITH (FORMAT CSV, HEADER)"
        ) as copy:
            copy.write(buf.read())

    # COPY expects the column order matching the table.
    # metrics_jsonb: time, labels, value
    # metrics_norm_brin: time, series_id, value
    # metrics_sharded: time, series_id, value (hash-partitioned by series)
    if variant == "sharded":
        cols = ["time", "series_id", "value"]
        table = "metrics_sharded"
        shards = int(os.environ.get("SHARDS", "1"))
        # The partitions are what the sharding scenario varies. Hash
        # partitioning on the series identity is what "shard by key" means
        # inside one instance: the query touches all of them, and
        # PostgreSQL scans them with Parallel Append.
        cur.execute("DROP TABLE IF EXISTS metrics_sharded")
        cur.execute(
            "CREATE TABLE metrics_sharded ("
            "  time      timestamptz      NOT NULL,"
            "  series_id int             NOT NULL,"
            "  value     double precision NOT NULL"
            ") PARTITION BY HASH (series_id)")
        cur.execute(
            "CREATE INDEX metrics_sharded_series_time_idx "
            "ON metrics_sharded (series_id, time)")
        for i in range(shards):
            cur.execute(
                f"CREATE TABLE metrics_sharded_p{i} PARTITION OF metrics_sharded "
                f"FOR VALUES WITH (MODULUS {shards}, REMAINDER {i})")
        print(f"[init] metrics_sharded: {shards} hash partitions", flush=True)
    elif variant == "norm":
        cols = ["time", "series_id", "value"]
        table = "metrics_norm_brin"
    else:
        cols = ["time", "labels", "value"]
        table = "metrics_jsonb"

    # Measure real COPY time instead of a hardcoded constant.
    t0 = time.monotonic()
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(cols)
    for r in sample_rows:
        writer.writerow(r)
    buf.seek(0)
    # psycopg v3 uses copy() not copy_from()
    with cur.copy(f"COPY {table} ({', '.join(cols)}) FROM STDIN WITH (FORMAT CSV, HEADER)") as copy:
        copy.write(buf.read())
    conn.commit()
    cur.close()
    conn.close()

    seconds = time.monotonic() - t0
    return {"samples": samples, "seconds": round(seconds, 1),
            "samples_per_second": round(samples / seconds, 1) if seconds > 0 else 0,
            "requests": 1}


def stop_load():
    """Quick probe: how many rows does the table have now?"""
    dsn = os.environ.get("PG_DSN")
    if not dsn:
        dsn = "postgres://bench:bench@postgres:5432/bench?sslmode=disable"
    try:
        conn = psycopg.connect(dsn, autocommit=True)
        cur = conn.cursor()
        for tbl in ["metrics_jsonb", "metrics_norm_brin"]:
            cur.execute(f"SELECT count(*) FROM {tbl}")
            n = cur.fetchone()[0]
            if n > 0:
                cur.close()
                conn.close()
                return {"series_present": n}
        cur.close()
        conn.close()
        return {"series_present": 0}
    except Exception:
        return {"series_present": 0}


